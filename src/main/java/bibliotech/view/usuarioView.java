    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        if (!validarCampos()) return;
        
        try {
            bibliotech.model.TipoUsuario tipo = bibliotech.model.TipoUsuario.valueOf(
                    cmbTipo.getSelectedItem().toString().toUpperCase());
            bibliotech.model.Usuario u = new bibliotech.model.Usuario(
                    txtNome.getText().trim(),
                    tipo,
                    txtMatricula.getText().trim(),
                    txtContato.getText().trim()
            );
            usuarioDAO.inserir(u);
            javax.swing.JOptionPane.showMessageDialog(this, "Usuário cadastrado com sucesso!");
            limparCampos();
            carregarTabela();
        } catch (SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao salvar: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = tblCadastrados.getSelectedRow();
        
        if (linha < 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione um usuário.");
            return;
        }
        try {
            String nome = (String) tblCadastrados.getValueAt(linha, 0);
            for (bibliotech.model.Usuario u : usuarioDAO.listar()) {
                if (u.getNome().equals(nome)) {
                    usuarioDAO.excluir(u.getId());
                    break;
                }
            }
            carregarTabela();
            javax.swing.JOptionPane.showMessageDialog(this, "Usuário excluído.");
        } catch (SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao excluir: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

