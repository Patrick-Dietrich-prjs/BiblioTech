    private void limparCampos() {
        txtNome.setText("");
        cmbTipo.setSelectedIndex(0);
        txtMatricula.setText("");
        txtContato.setText("");
        txtNome.requestFocus();
    }

    private boolean validarCampos() {
        if (txtNome.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Informe o nome.", "Atenção", javax.swing.JOptionPane.WARNING_MESSAGE);
            txtNome.requestFocus();
            return false;
        }
        return true;
    }
    
    private void carregarTabela() {
        try {
            DefaultTableModel model = (DefaultTableModel) tblCadastrados.getModel();
            model.setRowCount(0);
            for (bibliotech.model.Usuario u : usuarioDAO.listar()) {
                model.addRow(new Object[]{u.getNome(), u.getTipo().name(), u.getMatricula()});
            }
        } catch (SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao carregar usuários: " + ex.getMessage());
        }
    }
    
