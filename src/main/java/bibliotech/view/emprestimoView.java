    private void atualizarDataDevolucao() {
        try {
            java.util.Date dataRetirada = (java.util.Date) txtDataRetirada.getValue();
            if (dataRetirada != null) {
                java.util.Calendar cal = java.util.Calendar.getInstance();
                cal.setTime(dataRetirada);
                cal.add(java.util.Calendar.DAY_OF_MONTH, 7);
                txtDevolucao.setValue(cal.getTime());
            } else {
                txtDevolucao.setValue(null);
            }
        } catch (Exception e) {
            txtDevolucao.setValue(null);
        }
    }
    
    private void carregarCombos() {
        try {
            cmbUsuario.removeAllItems();
            listaUsuarios = usuarioDAO.listar();
            for (bibliotech.model.Usuario u : listaUsuarios) {
                cmbUsuario.addItem(u.getNome() + " (" + u.getTipo() + ")");
            }

            cmbLivro.removeAllItems();
            listaLivros = livroDAO.listarDisponiveis();
            for (bibliotech.model.Livro l : listaLivros) {
                cmbLivro.addItem(l.getTitulo() + " (disp: " + l.getQtdDisponivel() + ")");
            }
        } catch (SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao carregar dados: " + ex.getMessage());
        }
    }
    
