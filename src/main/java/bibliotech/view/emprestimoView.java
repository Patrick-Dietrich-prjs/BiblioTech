    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        int idxU = cmbUsuario.getSelectedIndex();
        int idxL = cmbLivro.getSelectedIndex();
        if (idxU < 0 || idxL < 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione usuário e livro.");
            return;
        }
        if (txtDataRetirada.getValue() == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Informe a data de retirada.");
            return;
        }
        try {
            java.util.Date dRet = (java.util.Date) txtDataRetirada.getValue();
            java.util.Date dDev = (java.util.Date) txtDevolucao.getValue();

            bibliotech.model.Emprestimo emp = new bibliotech.model.Emprestimo(
                    listaLivros.get(idxL),
                    listaUsuarios.get(idxU),
                    dRet.toInstant().atZone(java.time.ZoneId.systemDefault()).toLocalDate(),
                    dDev.toInstant().atZone(java.time.ZoneId.systemDefault()).toLocalDate()
            );
            emprestimoDAO.inserir(emp);
            javax.swing.JOptionPane.showMessageDialog(this, "Empréstimo registrado com sucesso!");
            carregarCombos(); // atualiza quantidades
            txtDataRetirada.setValue(null);
            txtDevolucao.setValue(null);
        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao registrar: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

