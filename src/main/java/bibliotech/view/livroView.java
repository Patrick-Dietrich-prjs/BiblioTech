    private void limparCampos() {
        txtTitulo.setText("");
        txtAutor.setText("");
        txtCategoria.setText("");
        ftxtQuantidade.setText("");
        txtTitulo.requestFocus();
    }

    private boolean validarCampos() {
        if (txtTitulo.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Informe o título.");
            return false;
        }
        if (txtAutor.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Informe o autor.");
            return false;
        }
        try {
            int qtd = Integer.parseInt(ftxtQuantidade.getText().trim());
            if (qtd <= 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Quantidade deve ser maior que zero.");
                return false;
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Quantidade inválida.");
            return false;
        }
        return true;
    }
    
    private void carregarTabela() {
        try {
            DefaultTableModel model = (DefaultTableModel) tblCadastrados.getModel();
            model.setRowCount(0);
            for (bibliotech.model.Livro l : livroDAO.listarTodos()) {
                model.addRow(new Object[]{l.getTitulo(), l.getAutor(), l.getQtdDisponivel()});
            }
        } catch (SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao carregar livros: " + ex.getMessage());
        }
    }
    
