    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        if (!validarCampos()) return;
        
        try {
            int qtd = Integer.parseInt(ftxtQuantidade.getText().trim());
            bibliotech.model.Livro livro = new bibliotech.model.Livro(
                    txtTitulo.getText().trim(),
                    txtAutor.getText().trim(),
                    txtCategoria.getText().trim(),
                    qtd
            );
            livroDAO.inserir(livro);
            javax.swing.JOptionPane.showMessageDialog(this, "Livro cadastrado com sucesso!");
            limparCampos();
            carregarTabela();
        } catch (SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao salvar: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = tblCadastrados.getSelectedRow();
        
        if (linha < 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione um livro.");
            return;
        }
        try {
            
            String titulo = (String) tblCadastrados.getValueAt(linha, 0);
            for (bibliotech.model.Livro l : livroDAO.listarTodos()) {
                if (l.getTitulo().equals(titulo)) {
                    livroDAO.excluir(l.getId());
                    break;
                }
            }
            carregarTabela();
            javax.swing.JOptionPane.showMessageDialog(this, "Livro excluído.");
        } catch (SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao excluir: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

