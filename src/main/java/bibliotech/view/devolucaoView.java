    private void btnDevolverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDevolverActionPerformed
        int linha = tblBusca.getSelectedRow();
        if (linha < 0) return;
        try {
            bibliotech.model.Emprestimo emp = listaAbertos.get(linha);
            emprestimoDAO.registrarDevolucao(emp.getId());
            javax.swing.JOptionPane.showMessageDialog(this, "Devolução registrada com sucesso!");
            carregarTabela();
            btnDevolver.setEnabled(false);
        } catch (SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao devolver: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnDevolverActionPerformed

