    private void carregarTabela() {
        try {
            javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblBusca.getModel();
            model.setRowCount(0);
            listaAbertos = emprestimoDAO.listarAbertos();
            for (bibliotech.model.Emprestimo e : listaAbertos) {
                String situacao = e.estaAtrasado() ? "ATRASADO" : "ATIVO";
                model.addRow(new Object[]{
                    e.getUsuario().getNome(),
                    e.getLivro().getTitulo(),
                    e.getDataPrevistaDevolucao().toString(),
                    situacao
                });
            }
        } catch (SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao carregar empréstimos: " + ex.getMessage());
        }
    }
    
